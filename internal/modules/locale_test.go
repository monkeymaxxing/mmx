// Stand-ins for the locale programs. locale -a lists $dir/available;
// locale-gen makes every enabled line of $dir/locale.gen available;
// update-locale sets variables in $dir/default (/etc/default/locale); and
// localectl keeps the system locale in $dir/conf, one setting a line,
// replacing all of them on set-locale, as the real one does. A file
// "fail-locale-gen" makes locale-gen fail, and "fail-default" makes
// update-locale and localectl set-locale fail.
var fakeLocalePrograms = map[string]string{
	"locale": `[ "$1" = -a ] && cat "$dir/available"`,
	"locale-gen": `[ ! -e "$dir/fail-locale-gen" ] || { echo "locale-gen: injected failure" >&2; exit 1; }
{ printf 'C\nC.utf8\nPOSIX\n'; grep -v '^[[:space:]]*#' "$dir/locale.gen" | awk 'NF == 2 {print $1}' | sed 's/\.UTF-8$/.utf8/'; } > "$dir/available"`,
	"update-locale": `[ ! -e "$dir/fail-default" ] || { echo "*** update-locale: Error: injected failure" >&2; exit 1; }
for a; do grep -v "^${a%%=*}=" "$dir/default" > "$dir/default.new"; echo "$a" >> "$dir/default.new"; mv "$dir/default.new" "$dir/default"; done`,
	"localectl": `case "$1" in
status)
  first=1
  while read -r s; do
    if [ $first = 1 ]; then echo "   System Locale: $s"; first=0; else echo "                  $s"; fi
  done < "$dir/conf"
  [ $first = 0 ] || echo "   System Locale: n/a"
  echo "       VC Keymap: (unset)";;
set-locale)
  [ ! -e "$dir/fail-default" ] || { echo "Failed to issue method call: Access denied" >&2; exit 1; }
  shift; : > "$dir/conf"; for a; do echo "$a" >> "$dir/conf"; done;;
esac`,
}

const fakeLocaleGen = "# This file lists locales that you wish to have built.\n# de_DE ISO-8859-1\n# de_DE.UTF-8 UTF-8\n# en_US.UTF-8 UTF-8\nen_US.UTF-8 UTF-8\n"

func localeFixture(t *testing.T) string {
	t.Helper()
	dir := standInPrograms(t, fakeLocalePrograms)
	writeState(t, filepath.Join(dir, "available"), "C\nC.utf8\nPOSIX\nen_US.utf8\n")
	writeState(t, filepath.Join(dir, "locale.gen"), fakeLocaleGen)
	writeState(t, filepath.Join(dir, "SUPPORTED"), "de_DE.UTF-8 UTF-8\nde_DE ISO-8859-1\nen_US.UTF-8 UTF-8\nfr_FR.UTF-8 UTF-8\nsr_RS@latin UTF-8\n")
	writeState(t, filepath.Join(dir, "default"), "#  File generated by update-locale\nLANG=en_US.UTF-8\nLC_TIME=\"en_GB.UTF-8\"\n")
	writeState(t, filepath.Join(dir, "conf"), "LANG=en_US.UTF-8\nLC_TIME=en_GB.UTF-8\n")
	for variable, path := range map[*string]string{&localeGenFile: "locale.gen", &supportedLocalesFile: "SUPPORTED", &debianDefaultLocaleFile: "default"} {
		previous := *variable
		*variable = filepath.Join(dir, path)
		t.Cleanup(func() { *variable = previous })
	}
	return dir
}

// The two values of use_as_system_default.
var (
	useAsDefault = true
	leaveDefault = false
)

// localeReads are the calls that only read.
var localeReads = []string{"locale -a", "localectl status"}

func TestLocaleIsMadeWithLocaleGenAndSetAsTheDefaultWithUpdateLocale(t *testing.T) {
	ctx := testContext(t)
	dir := localeFixture(t)
	l := Locale{Name: "de_DE.UTF-8", UseAsSystemDefault: &useAsDefault}
	want := map[string]any{"made_available": true, "system_default_before": "en_US.UTF-8", "system_default_after": "de_DE.UTF-8"}
	preview := noMutation(t).Locale(ctx, l, "apt")
	if preview.Status != "succeeded" || preview.Change != "would_change" || !reflect.DeepEqual(preview.Value, want) {
		t.Fatalf("%+v", preview)
	}
	if calls := changing(takeCalls(t, dir), localeReads...); calls != nil || readState(t, localeGenFile) != fakeLocaleGen {
		t.Fatal("dryrun changed the node", calls)
	}
	made := (Runtime{}).Locale(ctx, l, "apt")
	if made.Status != "succeeded" || made.Change != "changed" || !reflect.DeepEqual(made.Value, want) {
		t.Fatalf("%+v", made)
	}
	if calls := changing(takeCalls(t, dir), localeReads...); !reflect.DeepEqual(calls, []string{"locale-gen", "update-locale LANG=de_DE.UTF-8"}) {
		t.Fatal(calls)
	}
	// Only the line of this locale is enabled, where it was, and the other
	// settings of the default stay.
	if got := readState(t, localeGenFile); got != strings.Replace(fakeLocaleGen, "# de_DE.UTF-8 UTF-8", "de_DE.UTF-8 UTF-8", 1) {
		t.Fatal(got)
	}
	if got := readState(t, debianDefaultLocaleFile); !strings.Contains(got, "LANG=de_DE.UTF-8\n") || !strings.Contains(got, `LC_TIME="en_GB.UTF-8"`) {
		t.Fatal(got)
	}
	for _, run := range []Runtime{{}, noMutation(t)} {
		if r := run.Locale(ctx, l, "apt"); r.Status != "succeeded" || r.Change != "unchanged" || r.Value != nil {
			t.Fatalf("%+v", r)
		}
	}
	// use_as_system_default: false leaves the default alone.
	if r := (Runtime{}).Locale(ctx, Locale{Name: "en_US.UTF-8", UseAsSystemDefault: &leaveDefault}, "apt"); r.Change != "unchanged" {
		t.Fatalf("%+v", r)
	}
	// A locale that is available already is not made again; only the default changes.
	takeCalls(t, dir)
	r := (Runtime{}).Locale(ctx, Locale{Name: "en_US.UTF-8", UseAsSystemDefault: &useAsDefault}, "apt")
	if r.Change != "changed" || !reflect.DeepEqual(r.Value, map[string]any{"system_default_before": "de_DE.UTF-8", "system_default_after": "en_US.UTF-8"}) {
		t.Fatalf("%+v", r)
	}
	if calls := changing(takeCalls(t, dir), localeReads...); !reflect.DeepEqual(calls, []string{"update-locale LANG=en_US.UTF-8"}) {
		t.Fatal(calls)
	}
}

func TestLocaleAddsTheLineFromSupportedWhenLocaleGenListsOnlyEnabledLocales(t *testing.T) {
	ctx := testContext(t)
	dir := localeFixture(t)
	writeState(t, localeGenFile, "en_US.UTF-8 UTF-8\n")
	l := Locale{Name: "fr_FR.UTF-8", UseAsSystemDefault: &useAsDefault}
	if r := (Runtime{}).Locale(ctx, l, "apt"); r.Status != "succeeded" || r.Change != "changed" {
		t.Fatalf("%+v", r)
	}
	if got := readState(t, localeGenFile); got != "en_US.UTF-8 UTF-8\nfr_FR.UTF-8 UTF-8\n" {
		t.Fatal(got)
	}
	if calls := changing(takeCalls(t, dir), localeReads...); !reflect.DeepEqual(calls, []string{"locale-gen", "update-locale LANG=fr_FR.UTF-8"}) {
		t.Fatal(calls)
	}
	if r := (Runtime{}).Locale(ctx, l, "apt"); r.Change != "unchanged" {
		t.Fatalf("%+v", r)
	}
	// A locale neither file lists fails before any change.
	for _, run := range []Runtime{{}, {Dryrun: true}} {
		r := run.Locale(ctx, Locale{Name: "xx_YY.UTF-8", UseAsSystemDefault: &leaveDefault}, "apt")
		if r.Status != "failed" || r.FailureKind != "config" || !strings.Contains(r.Reason, "cannot make locale xx_YY.UTF-8") {
			t.Fatalf("%+v", r)
		}
	}
	if calls := changing(takeCalls(t, dir), localeReads...); calls != nil {
		t.Fatal(calls)
	}
}

func TestLocaleOnTheRedHatFamilyNamesTheLanguagePack(t *testing.T) {
	ctx := testContext(t)
	dir := localeFixture(t)
	os.Remove(localeGenFile)
	l := Locale{Name: "de_DE.UTF-8", UseAsSystemDefault: &useAsDefault}
	for run, status := range map[*Runtime]string{{Dryrun: true}: "not_checked", {}: "failed"} {
		if r := run.Locale(ctx, l, "dnf"); r.Status != status || !strings.Contains(r.Reason, "install the package glibc-langpack-de first with dnf_package") {
			t.Fatalf("%+v", r)
		}
	}
	if calls := changing(takeCalls(t, dir), localeReads...); calls != nil {
		t.Fatal(calls)
	}
	// Once the package is there, the default is set through localectl.
	writeState(t, filepath.Join(dir, "available"), "C.utf8\nde_DE.utf8\nen_US.utf8\n")
	r := (Runtime{}).Locale(ctx, l, "dnf")
	if r.Change != "changed" || !reflect.DeepEqual(r.Value, map[string]any{"system_default_before": "en_US.UTF-8", "system_default_after": "de_DE.UTF-8"}) {
		t.Fatalf("%+v", r)
	}
	if got := readState(t, filepath.Join(dir, "conf")); got != "LANG=de_DE.UTF-8\nLC_TIME=en_GB.UTF-8\n" {
		t.Fatal(got)
	}
	// A locale without a territory or with a modifier is compared as glibc lists it.
	writeState(t, filepath.Join(dir, "available"), "C.utf8\nsr_RS.utf8@latin\nde_DE\n")
	for _, name := range []string{"sr_RS.UTF-8@latin", "de_DE", "C.UTF-8"} {
		if r := (Runtime{}).Locale(ctx, Locale{Name: name, UseAsSystemDefault: &leaveDefault}, "dnf"); r.Status != "succeeded" || r.Change != "unchanged" {
			t.Fatal(name, r)
		}
	}
}

func TestLocaleFailures(t *testing.T) {
	ctx := testContext(t)
	dir := localeFixture(t)
	l := Locale{Name: "de_DE.UTF-8", UseAsSystemDefault: &useAsDefault}
	// locale-gen fails after the line was enabled: failed, changed; the next
	// try makes the locale with the line it finds enabled.
	writeState(t, filepath.Join(dir, "fail-locale-gen"), "")
	r := (Runtime{}).Locale(ctx, l, "apt")
	if r.Status != "failed" || r.Change != "changed" || !strings.Contains(r.Reason, "injected failure") || !strings.Contains(readState(t, localeGenFile), "\nde_DE.UTF-8 UTF-8\n") {
		t.Fatalf("%+v", r)
	}
	// The locale was not made, so the value says nothing was made.
	if r.Value != nil {
		t.Fatalf("a failed run reports a change that did not happen: %v", r.Value)
	}
	os.Remove(filepath.Join(dir, "fail-locale-gen"))
	// Then the default cannot be set: failed, changed.
	writeState(t, filepath.Join(dir, "fail-default"), "")
	r = (Runtime{}).Locale(ctx, l, "apt")
	if r.Status != "failed" || r.Change != "changed" || !strings.Contains(r.Reason, "update-locale") || !strings.Contains(readState(t, filepath.Join(dir, "available")), "de_DE.utf8") {
		t.Fatalf("%+v", r)
	}
	// The locale was made, and the default was not set.
	if !reflect.DeepEqual(r.Value, map[string]any{"made_available": true}) {
		t.Fatalf("a failed run reports %v", r.Value)
	}
	os.Remove(filepath.Join(dir, "fail-default"))
	if r := (Runtime{}).Locale(ctx, l, "apt"); r.Status != "succeeded" || r.Change != "changed" || readState(t, filepath.Join(dir, "calls")) == "" {
		t.Fatalf("%+v", r)
	}
	// localectl fails before anything changed: failed, unknown.
	writeState(t, filepath.Join(dir, "fail-default"), "")
	if r := (Runtime{}).Locale(ctx, Locale{Name: "C.UTF-8", UseAsSystemDefault: &useAsDefault}, "dnf"); r.Status != "failed" || r.Change != "unknown" || !strings.Contains(r.Reason, "Access denied") {
		t.Fatalf("%+v", r)
	}
	// A missing program names its package; dryrun cannot check yet. A test
	// machine with its own locale-gen, such as a Debian node, cannot show it.
	os.Remove(filepath.Join(dir, "locale-gen"))
	if _, err := exec.LookPath("locale-gen"); err != nil {
		for run, status := range map[*Runtime]string{{Dryrun: true}: "not_checked", {}: "failed"} {
			if r := run.Locale(ctx, l, "apt"); r.Status != status || !strings.Contains(r.Reason, missingProgramError("locale-gen").Error()) {
				t.Fatalf("%+v", r)
			}
		}
	}
	if r := (Runtime{}).Locale(ctx, l, "zypper"); r.Status != "failed" || !strings.Contains(r.Reason, `package manager is "zypper"`) {
		t.Fatalf("%+v", r)
	}
	for locale, message := range map[Locale]string{
		{UseAsSystemDefault: &useAsDefault}: "locale.name is required",
		{Name: "en_US.UTF-8"}:               "locale.use_as_system_default is required",
	} {
		if r := (Runtime{}).Locale(ctx, locale, "apt"); r.FailureKind != "config" || !strings.Contains(r.Reason, message) {
			t.Fatalf("%+v", r)
		}
	}
}

func TestLocaleRule(t *testing.T) {
	t.Parallel()
	for name, ok := range map[string]bool{
		"en_US.UTF-8": true, "de_DE": true, "sr_RS@latin": true, "ca_ES.UTF-8@valencia": true, "C.UTF-8": true, "POSIX": true,
		"en_US.UTF-8 UTF-8": false, "en_US/UTF-8": false, "_US": false, "en_US.": false, "": false,
	} {
		if err := localeRule(name); (err == nil) != ok {
			t.Error(name, err)
		}
	}
}
