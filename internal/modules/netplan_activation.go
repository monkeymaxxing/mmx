type netplanLink struct{ name, index string }
type netplanActivation struct {
	destination string
	data        netplanRestoreData
	links       []netplanLink
	flushed     []netplanLink
}

func newNetplanActivation(destination string, saved json.RawMessage) (ChangeActivation, error) {
	if filepath.Dir(destination) != netplanDirectories[0] || !netplanFileName.MatchString(filepath.Base(destination)) {
		return nil, fmt.Errorf("Cannot activate or restore %s: the saved destination must be a .yaml file in %s.", destination, netplanDirectories[0])
	}
	activation := &netplanActivation{destination: destination}
	if err := protocol.Decode(saved, &activation.data); err != nil {
		return nil, err
	}
	for _, names := range [][]string{activation.data.DevicesToRemove, activation.data.DevicesToRemoveOnRestore} {
		for index, name := range names {
			if !networkdDeviceName(name) || slices.Contains(names[:index], name) {
				return nil, fmt.Errorf("The saved Netplan device name %q is invalid or repeated.", name)
			}
		}
	}
	for _, names := range [][]string{activation.data.NetworkFilesToRemove, activation.data.NetworkFilesToRemoveOnRestore} {
		for index, name := range names {
			if filepath.Base(name) != name || !strings.HasPrefix(name, "10-netplan-") || !strings.HasSuffix(name, ".network") || strings.ContainsAny(name, "\x00\r\n\\") || slices.Contains(names[:index], name) {
				return nil, fmt.Errorf("The saved filename %q for a network file generated by Netplan is invalid or repeated.", name)
			}
		}
	}
	return activation, nil
}
func (a *netplanActivation) devices(restoring bool) []string {
	if restoring {
		return a.data.DevicesToRemoveOnRestore
	}
	return a.data.DevicesToRemove
}
func (a *netplanActivation) networkFiles(restoring bool) []string {
	if restoring {
		return a.data.NetworkFilesToRemoveOnRestore
	}
	return a.data.NetworkFilesToRemove
}
func netplanLinkProperties(index string) (map[string]string, error) {
	text, err := os.ReadFile(filepath.Join(netplanLinkStateDirectory, index))
	if err != nil {
		return nil, err
	}
	properties := map[string]string{}
	for _, setting := range networkdSettings(string(text)) {
		if setting.key != "" {
			properties[setting.key] = networkdValue(setting.value)
		}
	}
	return properties, nil
}
func netplanLinkIndex(name string) (string, error) {
	text, err := os.ReadFile(filepath.Join(networkdLinksDirectory, name, "ifindex"))
	if err != nil {
		return "", err
	}
	index := strings.TrimSpace(string(text))
	integer, err := strconv.Atoi(index)
	if err != nil || integer <= 0 {
		return "", fmt.Errorf("The kernel did not provide a valid network interface index for %s.", name)
	}
	return index, nil
}
func (a *netplanActivation) applyFailure(err error) error {
	return fmt.Errorf("Cannot apply %s with Netplan: %s", a.destination, err)
}
func (a *netplanActivation) findCardsFailure(err error) error {
	return fmt.Errorf("Cannot find the network interfaces configured by %s: %w", a.destination, err)
}
func (a *netplanActivation) PrepareActivation(ctx context.Context, run Runtime, restoring bool) error {
	if restoring {
		waitForNetworkdStartup(ctx, run)
	}
	a.links, a.flushed = nil, nil
	if len(a.networkFiles(restoring)) == 0 {
		return nil
	}
	entries, err := os.ReadDir(networkdLinksDirectory)
	if err != nil {
		return a.findCardsFailure(err)
	}
	for _, entry := range entries {
		name := entry.Name()
		// The kernel also keeps control files here, such as bonding_masters.
		if entry.Type().IsRegular() || !networkdDeviceName(name) {
			continue
		}
		index, err := netplanLinkIndex(name)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return a.findCardsFailure(err)
		}
		properties, err := netplanLinkProperties(index)
		if os.IsNotExist(err) {
			continue
		} // Links never managed by networkd.
		if err != nil {
			return a.findCardsFailure(err)
		}
		if properties["ADMIN_STATE"] == "unmanaged" {
			continue
		}
		for _, file := range a.networkFiles(restoring) {
			if properties["NETWORK_FILE"] == filepath.Join(netplanGeneratedDirectory, file) {
				a.links = append(a.links, netplanLink{name, index})
				break
			}
		}
	}
	return nil
}
func (a *netplanActivation) Activate(ctx context.Context, run Runtime, restoring bool) error {
	output := run.RunCommandThatChangesTheNode(ctx, []string{"netplan", "apply"}, "")
	if err := netplanCommandFailure(output); err != nil {
		return a.applyFailure(err)
	}
	return nil
}
func (a *netplanActivation) removalFailure(name string, err error) error {
	return fmt.Errorf("Cannot remove virtual network device %s declared by %s: %s.", name, a.destination, strings.TrimSuffix(err.Error(), "."))
}
func netplanCanDelete(name string) error {
	resolved, err := filepath.EvalSymlinks(filepath.Join(networkdLinksDirectory, name))
	if err != nil {
		return err
	}
	if !strings.HasPrefix(resolved, networkdVirtualDirectory+string(os.PathSeparator)) {
		return fmt.Errorf("the device is not below /sys/devices/virtual/net/")
	}
	files, err := readNetplanGeneratedFiles(netplanGeneratedDirectory)
	if err != nil {
		return err
	}
	devices, err := netplanDeviceSettings(files)
	if err != nil {
		return err
	}
	if _, exists := devices[name]; exists {
		return fmt.Errorf("a network file generated by Netplan in the active configuration still declares the virtual network device")
	}
	return nil
}
func (a *netplanActivation) deviceRemoved(name string) error {
	exists, err := networkdDeviceExists(name)
	if err != nil {
		return a.removalFailure(name, err)
	}
	if exists {
		return a.removalFailure(name, fmt.Errorf("the virtual network device still exists after networkctl reported successful deletion"))
	}
	return nil
}
func (a *netplanActivation) RemoveObsoleteVirtualDevices(ctx context.Context, run Runtime, restoring bool) error {
	// Check every identity together, because deleting a veth deletes its peer.
	check := func(name string) (bool, error) {
		exists, err := networkdDeviceExists(name)
		if err == nil && exists {
			err = netplanCanDelete(name)
		}
		if err != nil {
			return exists, a.removalFailure(name, err)
		}
		return exists, nil
	}
	for _, name := range a.devices(restoring) {
		if _, err := check(name); err != nil {
			return err
		}
	}
	for _, name := range a.devices(restoring) {
		// Recheck the full remaining list, including a veth peer, immediately
		// before each delete. Earlier deletions may have changed ownership.
		for _, remaining := range a.devices(restoring) {
			if _, err := check(remaining); err != nil {
				return err
			}
		}
		exists, err := check(name)
		if err != nil {
			return err
		}
		if !exists {
			continue
		}
		output := run.RunCommandThatChangesTheNode(ctx, []string{"networkctl", "delete", name}, "")
		if err := commandFailure(output, "Removing virtual device "+name); err != nil {
			return a.removalFailure(name, err)
		}
		if err := a.deviceRemoved(name); err != nil {
			return err
		}
	}
	return a.removeUnmanagedAddresses(ctx, run, restoring)
}
func (a *netplanActivation) addressFailure(name string, err error) error {
	return fmt.Errorf("Cannot remove the IP addresses on network interface %s configured by %s: %s.", name, a.destination, strings.TrimSuffix(err.Error(), "."))
}

// Netplan apply can return before networkd finishes. Wait only for links whose
// generated configuration disappeared, never for arbitrary network readiness.
func (a *netplanActivation) linkNeedsFlush(ctx context.Context, link netplanLink, restoring bool) (bool, error) {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	for {
		index, err := netplanLinkIndex(link.name)
		if os.IsNotExist(err) || (err == nil && index != link.index) {
			return false, nil
		}
		if err != nil {
			return false, err
		}
		properties, err := netplanLinkProperties(index)
		if err != nil && !os.IsNotExist(err) {
			return false, err
		}
		selected := properties["NETWORK_FILE"]
		removed := false
		for _, file := range a.networkFiles(restoring) {
			removed = removed || selected == filepath.Join(netplanGeneratedDirectory, file)
		}
		if selected != "" && !removed {
			return false, nil
		} // Another file took over.
		if properties["ADMIN_STATE"] == "unmanaged" {
			return true, nil
		}
		timer := time.NewTimer(50 * time.Millisecond)
		select {
		case <-ctx.Done():
			timer.Stop()
			return false, fmt.Errorf("systemd-networkd did not finish releasing the link within the cleanup wait: %w", ctx.Err())
		case <-timer.C:
		}
	}
}
func (a *netplanActivation) removeUnmanagedAddresses(ctx context.Context, run Runtime, restoring bool) error {
	for _, link := range a.links {
		flush, err := a.linkNeedsFlush(ctx, link, restoring)
		if err != nil {
			return a.addressFailure(link.name, err)
		}
		if !flush {
			continue
		}
		output := run.RunCommandThatChangesTheNode(ctx, []string{"ip", "address", "flush", "dev", link.name, "scope", "global"}, "")
		if err := commandFailure(output, "Removing global addresses from "+link.name); err != nil {
			return a.addressFailure(link.name, err)
		}
		a.flushed = append(a.flushed, link)
	}
	return nil
}
func (a *netplanActivation) CheckActivatedConfiguration(ctx context.Context, run Runtime, restoring bool) error {
	for _, name := range a.devices(restoring) {
		if err := a.deviceRemoved(name); err != nil {
			return err
		}
	}
	for _, link := range a.flushed {
		index, err := netplanLinkIndex(link.name)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return a.addressFailure(link.name, err)
		}
		if index != link.index {
			return a.addressFailure(link.name, fmt.Errorf("the network interface was replaced during IP address removal"))
		}
		output := run.RunCommand(ctx, []string{"ip", "-o", "address", "show", "dev", link.name, "scope", "global"}, "")
		if err := commandFailure(output, "Checking global addresses on "+link.name); err != nil {
			return a.addressFailure(link.name, err)
		}
		if strings.TrimSpace(output.StandardOutput) != "" {
			return a.addressFailure(link.name, fmt.Errorf("the network interface still has a global IP address after ip address flush"))
		}
	}
	return nil
}
