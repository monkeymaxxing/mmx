// restoreTarget reads MMX's record of the restore into data: the file named
// for the SHA-256 of the data directory's path, mode 0600. It returns nil
// when there is none.
func (n *postgresqlNode) restoreTarget(data string) map[string]any {
	n.t.Helper()
	sum := sha256.Sum256([]byte(data))
	path := filepath.Join(n.records, hex.EncodeToString(sum[:])+".json")
	text := n.read(path)
	if text == "" {
		return nil
	}
	if info, err := os.Stat(path); err != nil || info.Mode().Perm() != 0600 {
		n.t.Errorf("the record of the restore into %s: %v %v", data, info, err)
	}
	var record map[string]any
	if err := json.Unmarshal([]byte(text), &record); err != nil {
		n.t.Fatalf("the record of the restore into %s: %v: %s", data, err, text)
	}
	return record
}

// restoreTarget is the record of a restore of the stanza main into data.
func restoreTarget(data, recoverTo string, readRepositoryAsOf any) map[string]any {
	return map[string]any{"data_directory": data, "stanza": "main", "recover_to": recoverTo, "read_repository_as_of": readRepositoryAsOf}
}

// anotherTarget is the reason of a task whose target differs from the
// module's restore in data.
func anotherTarget(data, restored, asked string) string {
	return "pgbackrest_restore: " + data + " holds the module's restore of the stanza main to " + restored + ", and the task asks for the stanza main to " +
		asked + ". The module never writes over a cluster: to restore again, stop the cluster, empty " + data + ", and run the task again"
}

