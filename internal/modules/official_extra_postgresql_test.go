	expectStatus(t, node.run("pg_auto_failover_node", settingsInputs(data, "db01", settings, "on_a_replica"), false), "failed", "missing_prerequisite", refusal)
	expectPostgresqlCalls(t, node.calls(), c.showSystemd, c.unitState, c.showState, c.ready, c.ready, c.local, c.fileSettings, c.pgSettings)
	if node.read(node.settings) != settingsHeader+"shared_buffers = '1GB'\nwork_mem = '64MB'\n" {
		t.Errorf("the module's file holds %q", node.read(node.settings))
	}

	// A setting that needs no restart is no reason to refuse.
	node.stub("pg_settings", pgSettings("shared_buffers|postmaster|f|"+node.settings, "work_mem|user|f|"+node.settings))
	r = node.run("pg_auto_failover_node", settingsInputs(data, "db01", map[string]any{"shared_buffers": "1GB", "work_mem": "32MB"}, "on_a_replica"), false)
	expectResult(t, r, "succeeded", "changed", "set work_mem from 64MB to 32MB in "+settingsFile+"; reloaded PostgreSQL in "+data)
