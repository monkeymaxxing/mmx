// hbaWithoutInitdbTrust is initdb's pg_hba.conf with Debian's methods:
// socketMethod on the local socket's first line, peer for replication on
// the socket, and scram-sha-256 on the loopback addresses. pg_autoctl's own
// line keeps its trust.
func hbaWithoutInitdbTrust(socketMethod string) string {
	return strings.NewReplacer(
		"local   all             all                                     trust", "local   all             all                                     "+socketMethod,
		"local   replication     all                                     trust", "local   replication     all                                     peer",
		"127.0.0.1/32            trust", "127.0.0.1/32            scram-sha-256",
		"::1/128                 trust", "::1/128                 scram-sha-256").Replace(initdbHba)
}

