// run runs one node task as the node task execution engine reports it,
// with the two secrets of these tests in the task's scope, and checks that
// the result shows nothing of them and hides nothing.
func (n *postgresqlNode) run(name string, inputs map[string]any, dryrun bool) protocol.Result {
	n.t.Helper()
	scope, trace := taskScope(map[string]string{"autoctl_node_password": autoctlPasswordForTests, "replication_password": replicationPasswordForTests,
		"s3_key_secret": "Sentinel-s3"})
	r := Runtime{Dryrun: dryrun}.Starlark(testContext(n.t), name, n.module(name), inputs, scope)
	if r.Secret || trace.Used {
		n.t.Errorf("the task's result is hidden as a secret: %+v", r)
	}
	r = reportedByTheEngine(r, scope)
	r.Reason, r.Diff = n.real(r.Reason), n.real(r.Diff)
	if whole, _ := json.Marshal(r); strings.Contains(string(whole), "Sentinel") {
		n.t.Errorf("the result holds a secret: %s", whole)
	}
	return r
}

// calls returns the commands that the script ran since the last call of
// calls, in order, with the real paths. A command that runuser started is
// noted once, as runuser's.
func (n *postgresqlNode) calls() []string {
	n.t.Helper()
	var calls []string
	afterRunuser := false
	for _, line := range n.recorded() {
		if afterRunuser {
			afterRunuser = false
			continue
		}
		afterRunuser = strings.HasPrefix(line, "runuser ")
		calls = append(calls, n.real(line))
	}
	if strings.Contains(strings.Join(calls, "\n"), "Sentinel") {
		n.t.Errorf("a command line holds a secret: %q", calls)
	}
	if err := os.Remove(filepath.Join(n.stubs, "calls")); err != nil && !os.IsNotExist(err) {
		n.t.Fatal(err)
	}
	return calls
}

func expectPostgresqlCalls(t *testing.T, got []string, want ...string) {
	t.Helper()
	if !reflect.DeepEqual(got, want) {
		t.Errorf("calls:\n  %s\nwant:\n  %s", strings.Join(got, "\n  "), strings.Join(want, "\n  "))
	}
}

func expectStatus(t *testing.T, r protocol.Result, status, kind, reason string) {
	t.Helper()
	if r.Status != status || r.FailureKind != kind || r.Reason != reason {
		t.Errorf("status %q, kind %q, reason %q\n   want %q, %q, %q", r.Status, r.FailureKind, r.Reason, status, kind, reason)
	}
}

