// pgSettings is what psql prints for the module's query of pg_settings: a
// line name|context|pending_restart|sourcefile|setting for each setting, of
// which a line without the value that PostgreSQL runs with gets an empty
// one.
func pgSettings(lines ...string) string {
	for i, line := range lines {
		if strings.Count(line, "|") == 3 {
			lines[i] = line + "|"
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

// The calls of the settings in data, with the real paths.
type settingsCalls struct {
	showSystemd, unitState, showState, ready, local, fileSettings, pgSettings, checkConfiguration, controlFile, reload, restart, enableMaintenance, disableMaintenance string
}

func callsOfSettings(data string) settingsCalls {
	local := "runuser -u postgres -- /usr/lib/postgresql/18/bin/psql --no-psqlrc --quiet --no-align --tuples-only --set ON_ERROR_STOP=1 --port 5432 --dbname postgres"
	return settingsCalls{
		showSystemd:        "runuser -u postgres -- pg_autoctl -q show systemd --pgdata " + data,
		unitState:          "systemctl show pgautofailover.service --property=ActiveState --property=UnitFileState",
		showState:          "runuser -u postgres -- pg_autoctl show state --pgdata " + data + " --json",
		ready:              "pg_isready --quiet --port 5432",
		local:              local,
		fileSettings:       local + " --command select name, sourcefile, sourceline from pg_file_settings order by seqno",
		pgSettings:         local + " --command select name, context, pending_restart, sourcefile, setting from pg_settings order by name",
		checkConfiguration: "runuser -u postgres -- /usr/lib/postgresql/18/bin/postgres -D " + data + " -C port",
		controlFile:        "runuser -u postgres -- /usr/lib/postgresql/18/bin/pg_controldata -D " + data,
		reload:             "runuser -u postgres -- /usr/lib/postgresql/18/bin/pg_ctl reload --pgdata " + data,
		restart:            "systemctl restart pgautofailover.service",
		enableMaintenance:  "runuser -u postgres -- pg_autoctl enable maintenance --pgdata " + data,
		disableMaintenance: "runuser -u postgres -- pg_autoctl disable maintenance --pgdata " + data,
	}
}

// expectSettingsOutputs checks the outputs of the settings in a run.
