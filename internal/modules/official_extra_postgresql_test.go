// A pgbackrest stand-in. info prints info.json; stanza-create ends with the
// exit code in create_exit_code; check fails while check_fails exists, with
// what pgBackRest 2.58 printed for an archive_command that names another
// stanza; restore writes what a restore of pgBackRest leaves in the data
// directory.
const pgbackrestStandIn = `case "$*" in
*' info --output=json') cat "$STUBS/info.json" ;;
*' stanza-create') exit "$(cat "$STUBS/create_exit_code" 2>/dev/null || echo 0)" ;;
*' stanza-upgrade') ;;
*' check') if [ -e "$STUBS/check_fails" ]; then
  echo '2026-10-27 10:00:00.000 P00  ERROR: [082]: WAL segment 000000010000000000000003 was not archived before the 60000ms timeout' >&2
  echo '                                    HINT: check the archive_command to ensure that all options are correct (especially --stanza).' >&2
  exit 82; fi ;;
version) echo "pgBackRest $(cat "$STUBS/version")" ;;
*' restore') for argument in "$@"; do case "$argument" in --pg1-path=*) data=${argument#--pg1-path=} ;; esac; done
  echo 18 > "$data/PG_VERSION"; : > "$data/recovery.signal"
  printf "restore_command = 'pgbackrest --config=/etc/pgbackrest/pgbackrest.conf --pg1-path=%s --stanza=main archive-get %%f \\"%%p\\"'\n" "$data" > "$data/postgresql.auto.conf" ;;
*) echo "the test expects no call pgbackrest $*" >&2; exit 99 ;;
esac`

// The JSON of pgbackrest info for the stanza main. codes are the
// repositories' status codes; a stanza with backups lists two, which ended
// one second before and one second after 2026-10-27 09:55:48 UTC, which is
// 1793094948 seconds since 1970, as pgBackRest 2.58 printed for a backup
// that started then.
func pgbackrestInfo(code int, version string, backups bool) string {
	listed := `[]`
	if backups {
		listed = `[{"label": "20261027-095500F", "type": "full", "timestamp": {"start": 1793094900, "stop": 1793094947}},
		{"label": "20261027-095548D", "type": "diff", "timestamp": {"start": 1793094948, "stop": 1793094949}}]`
	}
	databases := `[]`
	if version != "" {
		databases = `[{"id": 1, "repo-key": 1, "system-id": 7701282236976114701, "version": "` + version + `"}]`
	}
	return `[{"archive": [], "backup": ` + listed + `, "cipher": "none", "db": ` + databases + `, "name": "main",
	  "repo": [{"cipher": "none", "key": 1, "status": {"code": ` + itoa(code) + `, "message": "made up"}}], "status": {"code": ` + itoa(code) + `, "message": "made up"}}]`
}

