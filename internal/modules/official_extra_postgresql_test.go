// What pg_autoctl's create commands leave in a new data directory, the
// directory after --pgdata: initdb's pg_hba.conf, and its pg_ident.conf of
// comments. A creation that runs again keeps the files.
const initdbFiles = `for argument in "$@"; do [ "$previous" = --pgdata ] && data=$argument; previous=$argument; done
  if [ -e "$STUBS/initdb_hba" ] && [ ! -e "$data/pg_hba.conf" ]; then mkdir -p "$data"; cp "$STUBS/initdb_hba" "$data/pg_hba.conf"
    printf '# PostgreSQL User Name Maps\n' > "$data/pg_ident.conf"; fi`

// pg_autoctl config set --pgdata DIRECTORY postgresql.listen_addresses
// VALUE writes the value into the configuration.
const configSet = `configuration=$(cat "$STUBS/configuration_path"); sed "s/^listen_addresses = .*/listen_addresses = $6/" "$configuration" > "$configuration.new"
  /bin/mv "$configuration.new" "$configuration"`

// A pg_autoctl stand-in for a monitor: create monitor writes its
// configuration; drop node takes the node out of the state.
const pgAutoctlOfAMonitor = `case "$*" in
'-q show systemd --pgdata '*) sed "s#@DIRECTORY@#$5#" "$STUBS/unit_text" ;;
'show state --pgdata '*) cat "$STUBS/state.json" ;;
'create monitor '*) mkdir -p "$(dirname "$(cat "$STUBS/configuration_path")")"; cp "$STUBS/configuration" "$(cat "$STUBS/configuration_path")"
  ` + initdbFiles + ` ;;
'config set --pgdata '*) ` + configSet + ` ;;
'create formation '*) ;;
'drop node '*) if [ -e "$STUBS/state_after_the_drop.json" ]; then cp "$STUBS/state_after_the_drop.json" "$STUBS/state.json"; fi ;;
'drop monitor '*) /bin/rm "$(cat "$STUBS/configuration_path")" ;;
*) echo "the test expects no call pg_autoctl $*" >&2; exit 99 ;;
esac`

func monitorInputs(data string, changes map[string]any) map[string]any {
	inputs := map[string]any{"data_directory": data, "postgresql_major_version": 18, "port": 5432, "host_name": "10.20.0.31", "listen_address": "10.20.0.31",
		"autoctl_node_password": "{{ .secrets.autoctl_node_password }}", "formation": "default", "node_names": []any{"db01", "db02"}, "nodes_not_listed": "remove"}
	for key, value := range changes {
		if value == nil {
			delete(inputs, key)
		} else {
			inputs[key] = value
		}
	}
	return inputs
}

