func nodeInputs(data string, changes map[string]any) map[string]any {
	inputs := map[string]any{"name": "db01", "data_directory": data, "postgresql_major_version": 18, "port": 5432, "host_name": "10.20.0.21", "listen_address": "10.20.0.21",
		"monitor_host_name": "10.20.0.31", "monitor_port": 5432, "autoctl_node_password": "{{ .secrets.autoctl_node_password }}",
		"replication_password": "{{ .secrets.replication_password }}", "formation": "default", "candidate_priority": 50, "replication_quorum": true}
	for key, value := range changes {
		if value == nil {
			delete(inputs, key)
		} else {
			inputs[key] = value
		}
	}
	return inputs
}

// stateOf is the JSON of pg_autoctl show state for one node db01 in a
// state, with its candidate priority.
func stateOf(current, assigned string, priority int) string {
	return `[{"health": 1, "node_id": 1, "group_id": 0, "nodehost": "10.20.0.21", "nodename": "db01", "nodeport": 5432, "nodecluster": "default",
  "formation_kind": "pgsql", "reported_lsn": "0/3000000", "candidate_priority": ` + itoa(priority) + `, "replication_quorum": true,
  "current_group_state": "` + current + `", "assigned_group_state": "` + assigned + `"}]`
}

// nodeOf is the JSON of one node of pg_autoctl show state, healthy, in one
// state that is both its current and its assigned state.
func nodeOf(name, state string) string {
	row := strings.TrimSuffix(strings.TrimPrefix(stateOf(state, state, 50), "["), "]")
	return strings.Replace(row, `"db01"`, `"`+name+`"`, 1)
}

func itoa(number int) string {
	b, _ := json.Marshal(number)
	return string(b)
}

