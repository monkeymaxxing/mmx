// postgresqlNode is a node whose PostgreSQL programs are stand-ins.
type postgresqlNode struct {
	t *testing.T
	// stubs is the stand-ins' directory: the PostgreSQL programs' directory
	// of the scripts too.
	stubs string
	// home is the home directory of postgres, unit pg_autoctl's unit file,
	// extensions the directory of PostgreSQL's extensions, records
	// pgbackrest_restore's directory of the targets of its restores, and
	// settings pg_auto_failover_node's file of PostgreSQL settings.
	home, unit, extensions, records, settings string
	// account runs the stand-ins in place of postgres and root, and group
	// is its group: the test's own.
	account, group string
	recorded       func() []string
}

func newPostgresqlNode(t *testing.T, tools map[string]string) *postgresqlNode {
	t.Helper()
	skipOutsideTheRepository(t)
	all := map[string]string{}
	for name, body := range postgresqlStandIns {
		all[name] = body
	}
	for name, body := range tools {
		all[name] = body
	}
	me, err := user.Current()
	if err != nil {
		t.Fatal(err)
	}
	group, err := user.LookupGroupId(me.Gid)
	if err != nil {
		t.Fatal(err)
	}
	node := &postgresqlNode{t: t, recorded: stubTools(t, all), home: t.TempDir(), extensions: t.TempDir(), account: me.Username, group: group.Name}
	node.stubs = stubToolsDirectory(t)
	node.unit = filepath.Join(t.TempDir(), "pgautofailover.service")
	node.records = filepath.Join(t.TempDir(), "pgbackrest_restore_targets")
	node.settings = filepath.Join(t.TempDir(), "pg_auto_failover_node_settings.conf")
	node.stub("settings_path", node.settings)
	node.write(filepath.Join(node.extensions, "pgautofailover.control"), "")
	return node
}

func (n *postgresqlNode) write(path, content string) {
	n.t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		n.t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		n.t.Fatal(err)
	}
}

func (n *postgresqlNode) read(path string) string {
	n.t.Helper()
	b, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		n.t.Fatal(err)
	}
	return string(b)
}

// stub writes a file of the stand-ins' directory, which the stand-ins read.
func (n *postgresqlNode) stub(name, content string) { n.write(filepath.Join(n.stubs, name), content) }

// module loads an official extra module from a copy that names the
// stand-ins' directory for PostgreSQL's programs, the test's directories
// for the unit, the extensions, the home directory of postgres, and the
// records of restores, and the test's account for postgres. Nothing else of
// the script differs.
func (n *postgresqlNode) module(name string) Module {
	n.t.Helper()
	source := filepath.Join(officialExtraModulesDirectory, name)
	script, err := os.ReadFile(filepath.Join(source, ModuleScriptFile))
	if err != nil {
		n.t.Fatal(err)
	}
	text := string(script)
	for _, replacement := range [][2]string{
		{`ACCOUNT = "postgres"`, `ACCOUNT = "` + n.account + `"`},
		{`POSTGRESQL_PROGRAMS = "/usr/lib/postgresql/%s/bin"`, `POSTGRESQL_PROGRAMS = "` + n.stubs + `"`},
		{`POSTGRESQL_PROGRAMS % version`, `POSTGRESQL_PROGRAMS`},
		{`POSTGRESQL_EXTENSIONS = "/usr/share/postgresql/%s/extension"`, `POSTGRESQL_EXTENSIONS = "` + n.extensions + `"`},
		{`POSTGRESQL_EXTENSIONS % version`, `POSTGRESQL_EXTENSIONS`},
		{`UNIT_FILE = "/etc/systemd/system/pgautofailover.service"`, `UNIT_FILE = "` + n.unit + `"`},
		{`RESTORE_TARGET_RECORDS = "/var/lib/mmx/pgbackrest_restore_targets"`, `RESTORE_TARGET_RECORDS = "` + n.records + `"`},
		{`MEMORY_FILE = "/proc/meminfo"`, `MEMORY_FILE = "` + filepath.Join(n.stubs, "meminfo") + `"`},
		{`SETTINGS_FILE = "/etc/postgresql/pg_auto_failover_node_settings.conf"`, `SETTINGS_FILE = "` + n.settings + `"`},
		{`    return account.home, None`, `    return "` + n.home + `", None`},
		{`owner = "root", group = "root"`, `owner = "` + n.account + `", group = "` + n.group + `"`},
		{`owner = "root", group = ACCOUNT`, `owner = "` + n.account + `", group = "` + n.group + `"`},
		{`group = ACCOUNT`, `group = "` + n.group + `"`},
		{`REPLICA_WAITS_FOR_THE_PRIMARY_SECONDS = 300`, `REPLICA_WAITS_FOR_THE_PRIMARY_SECONDS = 4`},
		{`KEEPER_READS_ITS_CONFIGURATION_SECONDS = 5`, `KEEPER_READS_ITS_CONFIGURATION_SECONDS = 0`},
		{`REPORT_WAIT_SECONDS = 120`, `REPORT_WAIT_SECONDS = 4`},
		{`FORMATION_SETTLES_SECONDS = 300`, `FORMATION_SETTLES_SECONDS = 2`},
		{`found.group == ACCOUNT`, `found.group == "` + n.group + `"`},
	} {
		if strings.Contains(text, replacement[0]) {
			text = strings.ReplaceAll(text, replacement[0], replacement[1])
		}
	}
	description, err := os.ReadFile(filepath.Join(source, ModuleDescriptionFile))
	if err != nil {
		n.t.Fatal(err)
	}
	directory := filepath.Join(n.t.TempDir(), name)
	n.write(filepath.Join(directory, ModuleScriptFile), text)
	n.write(filepath.Join(directory, ModuleDescriptionFile), string(description))
	read, err := ReadModuleDescription(directory, name)
	if err != nil {
		n.t.Fatal(err)
	}
	return Module{Kind: KindOfficialExtra, Description: read, Directory: directory}
}

