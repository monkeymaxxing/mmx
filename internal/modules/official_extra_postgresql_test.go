	refusal := "pg_auto_failover_node: the node db01 is the primary of the formation default, and shared_buffers takes a restart of PostgreSQL, which on the primary " +
		"is a failover: make another node the primary first with pg_auto_failover_primary, then run this task again; the earlier settings stay in effect"

	// A dryrun is not checked; a run writes, finds that shared_buffers
	// waits, puts back both files, and reloads again.
	expectStatus(t, node.run("pg_auto_failover_node", settingsInputs(data, "db01", settings, "on_a_replica"), true), "not_checked", "", refusal)
	expectPostgresqlCalls(t, node.calls(), c.showSystemd, c.unitState, c.showState, c.ready, c.local, c.pgSettings, valueCall(data, "shared_buffers", "1GB"))
	for _, restart := range []string{"on_a_replica", "on_a_replica_or_a_node_alone"} {
		node.stub("pg_settings", pgSettings("shared_buffers|postmaster|f|"+data+"/postgresql-auto-failover.conf", "work_mem|user|f|"))
		node.stub("pg_settings_after_reload", pgSettings("shared_buffers|postmaster|t|"+data+"/postgresql-auto-failover.conf", "work_mem|user|f|"+node.settings))
		r := node.run("pg_auto_failover_node", settingsInputs(data, "db01", settings, restart), false)
		expectStatus(t, r, "failed", "missing_prerequisite", refusal)
		expectPostgresqlCalls(t, node.calls(), c.showSystemd, c.unitState, c.showState, c.ready, c.ready, c.local, c.checkConfiguration, c.fileSettings, c.reload,
			c.pgSettings, c.reload)
		if _, err := os.Stat(node.settings); !os.IsNotExist(err) || node.read(conf) != postgresqlConf {
			t.Errorf("%s: the refusal left the module's file or the include line", restart)
		}
	}

	// never: work_mem is live, and shared_buffers waits for a switchover.
	node.stub("pg_settings", pgSettings("shared_buffers|postmaster|f|"+data+"/postgresql-auto-failover.conf", "work_mem|user|f|"))
	node.stub("pg_settings_after_reload", pgSettings("shared_buffers|postmaster|t|"+data+"/postgresql-auto-failover.conf", "work_mem|user|f|"+node.settings))
	r := node.run("pg_auto_failover_node", settingsInputs(data, "db01", settings, "never"), false)
	expectResult(t, r, "succeeded", "changed", "set shared_buffers to 1GB and work_mem to 64MB in "+settingsFile+"; added the line "+settingsInclude+" at the end of "+conf+
		"; reloaded PostgreSQL in "+data+"; shared_buffers waits for a restart of PostgreSQL; make another node the primary with pg_auto_failover_primary, then run "+
		"this task with restart_postgresql_for_new_settings: on_a_replica on this node")
	expectSettingsOutputs(t, r, []any{"shared_buffers", "work_mem"}, false, []any{"shared_buffers"})
