// The module page generator writes docs/reference/modules/<module>.md for each core
// module from its page source internal/modules/<module>.md and its
// description in the registry, and the index docs/reference/modules/README.md. Run it
// from the repository root with go generate ./docs/reference/modules. The documentation
// map (docs/changing-mmx/documentation-map.md, "Module pages") owns the rules.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"

	"mmx/internal/config"
	"mmx/internal/modules"
)

// The directories of the page sources and of the generated pages, relative
// to the repository root, with slashes.
const (
	pageSourceDirectory     = "internal/modules"
	generatedPageDirectory  = "docs/reference/modules"
	officialExtraModulesDir = "official_extra_modules"
)

// generatedFileMarker starts the first line of every generated file.
const generatedFileMarker = "<!-- Generated by go generate ./docs/reference/modules"

// pageSectionsInOrder are the sections of a module page below its title and
// introduction, in their order on the page. The documentation map's table
// "The sections of a module page" lists the same sections.
var pageSectionsInOrder = []string{
	"Set up",
	"Inputs",
	"Outputs",
	"What a dryrun reports",
	"Retries and time limits",
	"Examples",
	"How it works",
	"Errors and what they mean",
	"Tested on",
	"Why it works this way",
}

// generatedSections come from the module's description; a page source never
// holds them.
var generatedSections = []string{"Inputs", "Outputs", "What a dryrun reports", "Retries and time limits"}

// requiredSourceSections must be in every page source. A "Tested on" section
// starts with the line "**Distributions:** ...", which the module index shows
// in its "Tested on" column.
var requiredSourceSections = []string{"Examples", "Tested on"}

// distributionsLine matches the first line of a "Tested on" section.
var distributionsLine = regexp.MustCompile(`^\*\*Distributions:\*\* (\S.*[^.\s])\.$`)

func main() {
	root, err := findRepositoryRoot()
	if err == nil {
		err = writeGeneratedPages(root)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "module page generator:", err)
		os.Exit(1)
	}
}

// findRepositoryRoot returns the directory that holds go.mod, starting at
// the current directory: go generate runs the generator in docs/reference/modules.
func findRepositoryRoot() (string, error) {
	directory, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(directory, "go.mod")); err == nil {
			return directory, nil
		}
		parent := filepath.Dir(directory)
		if parent == directory {
			return "", errors.New("no go.mod in the current directory or its parents; run go generate ./docs/reference/modules from the repository")
		}
		directory = parent
	}
}

// writeGeneratedPages writes every generated file that changed, removes
// generated pages that no core module has any more, and names on standard
// error each core module whose page source is missing.
func writeGeneratedPages(root string) error {
	generated, missingSources, err := generatePages(root)
	if err != nil {
		return err
	}
	for _, module := range missingSources {
		fmt.Fprintf(os.Stderr, "module page generator: core module %s has no page source %s/%s.md; its page is not generated\n", module, pageSourceDirectory, module)
	}
	output := filepath.Join(root, filepath.FromSlash(generatedPageDirectory))
	existing, err := filepath.Glob(filepath.Join(output, "*.md"))
	if err != nil {
		return err
	}
	for _, file := range existing {
		if _, keep := generated[filepath.Base(file)]; keep {
			continue
		}
		text, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(text, []byte(generatedFileMarker)) {
			if err := os.Remove(file); err != nil {
				return err
			}
		}
	}
	for name, text := range generated {
		file := filepath.Join(output, name)
		if old, err := os.ReadFile(file); err == nil && bytes.Equal(old, text) {
			continue
		}
		if err := os.WriteFile(file, text, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// generatePages returns the generated files of docs/reference/modules by file name, and
// the core modules that have no page source.
func generatePages(root string) (map[string][]byte, []string, error) {
	descriptionFiles, err := findDescriptionFiles(root)
	if err != nil {
		return nil, nil, err
	}
	generated := map[string][]byte{}
	var missingSources []string
	var problems []error
	for _, module := range modules.CoreModules() {
		sourceFile := filepath.Join(root, filepath.FromSlash(pageSourceDirectory), module.Name+".md")
		text, err := os.ReadFile(sourceFile)
		if errors.Is(err, os.ErrNotExist) {
			missingSources = append(missingSources, module.Name)
			continue
		}
		if err != nil {
			return nil, nil, err
		}
		source, err := parsePageSource(module.Name, string(text))
		if err != nil {
			problems = append(problems, err)
			continue
		}
		page, err := renderPage(module, source, descriptionFiles[module.Name])
		if err != nil {
			problems = append(problems, err)
			continue
		}
		generated[module.Name+".md"] = []byte(page)
	}
	if len(problems) > 0 {
		return nil, nil, errors.Join(problems...)
	}
	index, err := renderIndex(root, generated)
	if err != nil {
		return nil, nil, err
	}
	generated["README.md"] = []byte(index)
	return generated, missingSources, nil
}

// findDescriptionFiles returns, for each core module, the file in
// internal/modules that holds its Description value.
func findDescriptionFiles(root string) (map[string]string, error) {
	directory := filepath.Join(root, filepath.FromSlash(pageSourceDirectory))
	files, err := filepath.Glob(filepath.Join(directory, "*.go"))
	if err != nil {
		return nil, err
	}
	found := map[string]string{}
	fileSet := token.NewFileSet()
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		parsed, err := parser.ParseFile(fileSet, file, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		ast.Inspect(parsed, func(node ast.Node) bool {
			literal, ok := node.(*ast.CompositeLit)
			if !ok {
				return true
			}
			if typeName, ok := literal.Type.(*ast.Ident); !ok || typeName.Name != "Description" {
				return true
			}
			for _, element := range literal.Elts {
				pair, ok := element.(*ast.KeyValueExpr)
				if !ok {
					continue
				}
				key, ok := pair.Key.(*ast.Ident)
				value, isText := pair.Value.(*ast.BasicLit)
				if ok && key.Name == "Name" && isText && value.Kind == token.STRING {
					if name, err := strconv.Unquote(value.Value); err == nil {
						found[name] = pageSourceDirectory + "/" + filepath.Base(file)
					}
				}
			}
			return true
		})
	}
	return found, nil
}

// pageSource is a module's page source: its title line, the introduction
// below it, and its sections.
type pageSource struct {
	Title        string
	Introduction string
	Sections     []pageSection
}

// pageSection is one "## " section: its heading without the "## ", and its
// text up to the next "## " heading.
type pageSection struct {
	Heading string
	Text    string
}

// parsePageSource splits a page source into its parts and checks them: the
// title is the module's name in backticks, every section is one of
// pageSectionsInOrder in that order, none is generated, and the required
// sections are present.
func parsePageSource(moduleName, text string) (pageSource, error) {
	file := pageSourceDirectory + "/" + moduleName + ".md"
	var problems []error
	problem := func(format string, values ...any) {
		problems = append(problems, fmt.Errorf(file+": "+format, values...))
	}
	lines := strings.Split(strings.TrimSuffix(text, "\n"), "\n")
	wantTitle := "# `" + moduleName + "`"
	var source pageSource
	if len(lines) == 0 || lines[0] != wantTitle {
		problem("the first line must be the title %s", wantTitle)
		return source, errors.Join(problems...)
	}
	source.Title = lines[0]
	var current *pageSection
	var body []string
	finish := func() {
		joined := strings.Trim(strings.Join(body, "\n"), "\n")
		if current == nil {
			source.Introduction = joined
		} else {
			current.Text = joined
			source.Sections = append(source.Sections, *current)
		}
		body = nil
	}
	lastPosition := -1
	for number, line := range linesOutsideCodeFences(lines[1:]) {
		if !line.outsideCodeFence {
			body = append(body, line.text)
			continue
		}
		if strings.HasPrefix(line.text, "# ") {
			problem("line %d: a page has one title; %q is a second one", number+2, line.text)
		}
		heading, isSection := strings.CutPrefix(line.text, "## ")
		if !isSection {
			body = append(body, line.text)
			continue
		}
		heading = strings.TrimSpace(heading)
		position := slices.Index(pageSectionsInOrder, heading)
		switch {
		case slices.Contains(generatedSections, heading):
			problem("the section %q is generated from the module's description; remove it from the page source", "## "+heading)
		case position < 0:
			problem("%q is not a section of a module page; the documentation map lists them in its table \"The sections of a module page\"", "## "+heading)
		case position <= lastPosition:
			problem("the section %q is out of order; the order is: %s", "## "+heading, strings.Join(pageSectionsInOrder, ", "))
		default:
			lastPosition = position
		}
		finish()
		current = &pageSection{Heading: heading}
	}
	finish()
	for _, required := range requiredSourceSections {
		if !slices.ContainsFunc(source.Sections, func(s pageSection) bool { return s.Heading == required }) {
			problem("the required section %q is missing", "## "+required)
		}
	}
	for _, section := range source.Sections {
		if section.Heading == "Tested on" && testedOnDistributions(section.Text) == "" {
			problem(`the section "## Tested on" must start with a line like "**Distributions:** Debian 12 and 13, Ubuntu 24.04 and 26.04." that names the distributions`)
		}
	}
	return source, errors.Join(problems...)
}

// testedOnDistributions is the distributions that the first line of a
// "Tested on" section names, or "" when the section does not start with the
// line.
func testedOnDistributions(sectionText string) string {
	first, _, _ := strings.Cut(sectionText, "\n")
	if match := distributionsLine.FindStringSubmatch(first); match != nil {
		return match[1]
	}
	return ""
}

// testedOnInPage is the distributions in the "Tested on" section of a page.
func testedOnInPage(page string) string {
	_, section, found := strings.Cut(page, "\n## Tested on\n")
	if !found {
		return ""
	}
	return testedOnDistributions(strings.TrimLeft(section, "\n"))
}

// markdownLine is one line of a Markdown file, and whether it is outside a
// fenced code block (fence lines themselves count as inside).
type markdownLine struct {
	text             string
	outsideCodeFence bool
}

// codeFence matches a line that opens or closes a fenced code block.
var codeFence = regexp.MustCompile("^ {0,3}(`{3,}|~{3,})")

func linesOutsideCodeFences(lines []string) []markdownLine {
	var marked []markdownLine
	openFence := ""
	for _, line := range lines {
		fence := codeFence.FindStringSubmatch(line)
		switch {
		case openFence == "" && fence != nil:
			openFence = fence[1]
			marked = append(marked, markdownLine{line, false})
		case openFence != "":
			if fence != nil && fence[1][0] == openFence[0] && len(fence[1]) >= len(openFence) && strings.TrimSpace(line[strings.Index(line, fence[1])+len(fence[1]):]) == "" {
				openFence = ""
			}
			marked = append(marked, markdownLine{line, false})
		default:
			marked = append(marked, markdownLine{line, true})
		}
	}
	return marked
}

// The two forms of a link whose target is a path: an inline link
// [text](target "title") and a reference definition [label]: target.
var (
	inlineLinkTarget        = regexp.MustCompile(`\]\(([^()\s]+)((?:\s+"[^"]*")?)\)`)
	referenceDefinitionLine = regexp.MustCompile(`^( {0,3}\[[^\]]+\]:\s+)(\S+)(.*)$`)
)

// replaceLinkTargets calls replace for the target of every link outside code
// fences and code spans, and returns the text with the targets it returns.
func replaceLinkTargets(text string, replace func(target string) string) string {
	lines := strings.Split(text, "\n")
	for number, line := range linesOutsideCodeFences(lines) {
		if !line.outsideCodeFence {
			continue
		}
		if parts := referenceDefinitionLine.FindStringSubmatch(line.text); parts != nil {
			lines[number] = parts[1] + replace(parts[2]) + parts[3]
			continue
		}
		var rewritten strings.Builder
		for _, segment := range splitCodeSpans(line.text) {
			if segment.isCode {
				rewritten.WriteString(segment.text)
				continue
			}
			rewritten.WriteString(inlineLinkTarget.ReplaceAllStringFunc(segment.text, func(link string) string {
				parts := inlineLinkTarget.FindStringSubmatch(link)
				return "](" + replace(parts[1]) + parts[2] + ")"
			}))
		}
		lines[number] = rewritten.String()
	}
	return strings.Join(lines, "\n")
}

// textSegment is a part of a line: inline code, or text around it.
type textSegment struct {
	text   string
	isCode bool
}

// splitCodeSpans splits a line into inline code spans and the text around
// them. A run of backticks without a closing run of the same length is text.
func splitCodeSpans(line string) []textSegment {
	var segments []textSegment
	textStart := 0
	for i := 0; i < len(line); {
		if line[i] != '`' {
			i++
			continue
		}
		run := 1
		for i+run < len(line) && line[i+run] == '`' {
			run++
		}
		closing := findBacktickRun(line, i+run, run)
		if closing < 0 {
			i += run
			continue
		}
		segments = append(segments, textSegment{line[textStart:i], false}, textSegment{line[i : closing+run], true})
		i = closing + run
		textStart = i
	}
	return append(segments, textSegment{line[textStart:], false})
}

// findBacktickRun returns where a run of exactly length backticks starts at
// or after start, or -1.
func findBacktickRun(line string, start, length int) int {
	for i := start; i < len(line); {
		if line[i] != '`' {
			i++
			continue
		}
		run := 1
		for i+run < len(line) && line[i+run] == '`' {
			run++
		}
		if run == length {
			return i
		}
		i += run
	}
	return -1
}

// urlScheme matches a link target that starts with a scheme, such as
// https: or mailto:.
var urlScheme = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9+.-]*:`)

// isPathLink reports whether a link target is a relative path, which may end
// in an anchor; a target that is only an anchor is not.
func isPathLink(target string) bool {
	return target != "" && !urlScheme.MatchString(target) && !strings.HasPrefix(target, "/") && !strings.HasPrefix(target, "#")
}

// linkForGeneratedPage rewrites a link target of a page source, relative to
// internal/modules/, so that it works from docs/reference/modules/: a page source
// becomes its generated page beside it.
func linkForGeneratedPage(target string) string {
	if !isPathLink(target) {
		return target
	}
	linkPath, anchor, hasAnchor := strings.Cut(target, "#")
	resolved := path.Clean(path.Join(pageSourceDirectory, linkPath))
	var rewritten string
	if path.Dir(resolved) == pageSourceDirectory && path.Ext(resolved) == ".md" {
		rewritten = path.Base(resolved)
	} else {
		relative, err := filepath.Rel(filepath.FromSlash(generatedPageDirectory), filepath.FromSlash(resolved))
		if err != nil {
			return target
		}
		rewritten = filepath.ToSlash(relative)
		if strings.HasSuffix(linkPath, "/") {
			rewritten += "/"
		}
	}
	if hasAnchor {
		rewritten += "#" + anchor
	}
	return rewritten
}

// renderPage joins a page source and the module's description into the
// generated page.
func renderPage(module modules.CoreModule, source pageSource, descriptionFile string) (string, error) {
	described, err := config.Describe(module.Name)
	if err != nil {
		return "", err
	}
	if descriptionFile == "" {
		return "", fmt.Errorf("no Description value with Name %q in %s", module.Name, pageSourceDirectory)
	}
	sourceFile := pageSourceDirectory + "/" + module.Name + ".md"
	var page strings.Builder
	fmt.Fprintf(&page, "%s from %s and the module's description in %s. Edit those files, then run go generate ./docs/reference/modules; never edit this file. -->\n", generatedFileMarker, sourceFile, descriptionFile)
	page.WriteString(source.Title + "\n")
	if source.Introduction != "" {
		page.WriteString("\n" + replaceLinkTargets(source.Introduction, linkForGeneratedPage) + "\n")
	}
	generated := map[string]string{
		"Inputs":                  renderInputs(described.Fields),
		"Outputs":                 renderOutputs(described.Results),
		"What a dryrun reports":   asSentence(described.Dryrun) + "\n",
		"Retries and time limits": renderRetriesAndTimeLimits(module, described.Retry),
	}
	for _, heading := range pageSectionsInOrder {
		text, isGenerated := generated[heading]
		if !isGenerated {
			index := slices.IndexFunc(source.Sections, func(s pageSection) bool { return s.Heading == heading })
			if index < 0 {
				continue
			}
			text = replaceLinkTargets(source.Sections[index].Text, linkForGeneratedPage) + "\n"
		}
		page.WriteString("\n## " + heading + "\n\n" + text)
	}
	return page.String(), nil
}

// renderInputs writes one list item for each input: its name, its type or
// allowed values, whether it is required or its default, and its notes.
func renderInputs(fields []modules.Field) string {
	if len(fields) == 0 {
		return "The module takes no inputs.\n"
	}
	var text strings.Builder
	for _, field := range fields {
		kind := escapeMarkdown(field.Type)
		if len(field.Values) > 0 {
			var values []string
			for _, value := range field.Values {
				values = append(values, "`"+value+"`")
			}
			kind = joinAlternatives(values)
		}
		presence := "optional"
		if field.Required {
			presence = "required"
		} else if field.Default != "" {
			presence = "default " + defaultValue(field.Default)
		}
		fmt.Fprintf(&text, "- `%s` (%s; %s)", field.Name, kind, presence)
		if field.Notes != "" {
			text.WriteString(": " + escapeMarkdown(field.Notes))
		}
		text.WriteString("\n")
	}
	return text.String()
}

// renderOutputs lists the result fields that later node tasks read.
func renderOutputs(results []string) string {
	var text strings.Builder
	text.WriteString("The node task's result holds these fields. A later node task reads them as `.node_tasks.<id>.<field>`, where `<id>` is the node task's `id`.\n\n")
	for _, result := range results {
		text.WriteString("- `" + result + "`\n")
	}
	return text.String()
}

// renderRetriesAndTimeLimits says whether the node task tries again by
// default and which time limits it takes.
func renderRetriesAndTimeLimits(module modules.CoreModule, retry string) string {
	text := asSentence(retry) + "\n"
	if !module.WaitsWithItsOwnLimit {
		text += "\nThe node task takes the time limits `time_limit` and `time_limit_per_try`; without them, the project's `node_task_defaults` apply. `mmx describe-module task` describes the settings every node task accepts.\n"
	}
	return text
}

// joinAlternatives writes "a", "a or b", or "a, b, or c".
func joinAlternatives(values []string) string {
	switch len(values) {
	case 1:
		return values[0]
	case 2:
		return values[0] + " or " + values[1]
	}
	return strings.Join(values[:len(values)-1], ", ") + ", or " + values[len(values)-1] //nolint:nilaway // renderInputs calls joinAlternatives only after appending alternatives from a nonempty list.
}

// defaultValue writes a default that is one literal value as code, and a
// default that explains itself as text.
func defaultValue(value string) string {
	if strings.ContainsAny(value, " `") {
		return escapeMarkdown(value)
	}
	return "`" + value + "`"
}

// escapeMarkdown keeps a description's plain text plain on a rendered page.
// An asterisk could start emphasis, <name> could read as an HTML tag, and a
// backslash could escape the next character. A word or a quoted text that
// holds one of them, such as /etc/cron.d/<name> or "15 3 * * *", becomes
// code, which both a browser and a terminal show as written. Text that is
// already code stays as it is.
func escapeMarkdown(text string) string {
	var out strings.Builder
	for _, part := range codeSpanOrText.FindAllString(text, -1) {
		if strings.HasPrefix(part, "`") {
			out.WriteString(part)
			continue
		}
		out.WriteString(quotedTextOrWord.ReplaceAllStringFunc(part, func(word string) string {
			if !strings.ContainsAny(word, `<>*\`) {
				return word
			}
			if strings.HasPrefix(word, `"`) {
				return "`" + word + "`"
			}
			start := strings.IndexFunc(word, func(r rune) bool { return !strings.ContainsRune("([{", r) })
			end := strings.LastIndexFunc(word, func(r rune) bool { return !strings.ContainsRune(";,.:)]}", r) }) + 1
			if start < 0 || end <= start {
				return "`" + word + "`"
			}
			return word[:start] + "`" + word[start:end] + "`" + word[end:]
		}))
	}
	return out.String()
}

var (
	codeSpanOrText   = regexp.MustCompile("`[^`]*`|[^`]+")
	quotedTextOrWord = regexp.MustCompile(`"[^"]*"|[^\s"]+`)
)

// asSentence starts a description's text with a capital letter and ends it
// with a period.
func asSentence(text string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return text
	}
	if first := text[0]; first >= 'a' && first <= 'z' {
		text = string(first-'a'+'A') + text[1:]
	}
	if !strings.HasSuffix(text, ".") {
		text += "."
	}
	return escapeMarkdown(text)
}

// renderIndex writes docs/reference/modules/README.md: the core modules by topic, then
// the official extra modules.
func renderIndex(root string, generated map[string][]byte) (string, error) {
	var index strings.Builder
	fmt.Fprintf(&index, "%s from the core modules' descriptions in %s/*.go and their page sources %s/*.md, and from %s/*/%s. Edit those files, then run go generate ./docs/reference/modules; never edit this file. -->\n", generatedFileMarker, pageSourceDirectory, pageSourceDirectory, officialExtraModulesDir, modules.ModuleDescriptionFile)
	index.WriteString("# Module pages\n\n")
	index.WriteString("Each page describes one module of MMX: what it manages, its inputs and outputs, examples, how it works, its errors, where it is tested, and why it works this way. `mmx describe-module NAME` prints the same page in a terminal.\n")
	for _, topic := range modules.CoreModuleTopics {
		index.WriteString("\n## " + topic + "\n\n| Module | What it does | Tested on |\n|---|---|---|\n")
		for _, module := range modules.CoreModules() {
			if module.Description.Topic != topic {
				continue
			}
			summary := escapeMarkdown(module.Description.Summary)
			if page, hasPage := generated[module.Name+".md"]; hasPage {
				fmt.Fprintf(&index, "| [`%s`](%s.md) | %s | %s |\n", module.Name, module.Name, summary, escapeMarkdown(testedOnInPage(string(page))))
			} else {
				fmt.Fprintf(&index, "| `%s` (its page is not written yet) | %s | |\n", module.Name, summary)
			}
		}
	}
	index.WriteString("\n## Official extra modules\n\n")
	index.WriteString("These modules are Starlark scripts that ship with MMX in `official_extra_modules/` beside `mmx`. Each one's page is the `README.md` in its directory.\n\n| Module | What it does | Tested on |\n|---|---|---|\n")
	extras, err := os.ReadDir(filepath.Join(root, officialExtraModulesDir))
	if err != nil {
		return "", err
	}
	var names []string
	for _, entry := range extras {
		if entry.IsDir() && modules.ModuleName.MatchString(entry.Name()) {
			names = append(names, entry.Name())
		}
	}
	sort.Strings(names)
	for _, name := range names {
		description, err := modules.ReadModuleDescription(filepath.Join(root, officialExtraModulesDir, name), name)
		if err != nil {
			return "", err
		}
		readme, err := os.ReadFile(filepath.Join(root, officialExtraModulesDir, name, "README.md"))
		if err != nil {
			return "", err
		}
		tested := testedOnInPage(string(readme))
		if tested == "" {
			return "", fmt.Errorf("%s/%s/README.md: the section \"## Tested on\" must start with a line like \"**Distributions:** Debian 12 and 13, Ubuntu 24.04 and 26.04.\"", officialExtraModulesDir, name)
		}
		fmt.Fprintf(&index, "| [`%s`](../../../%s/%s/README.md) | %s | %s |\n", name, officialExtraModulesDir, name, escapeMarkdown(strings.TrimSpace(description.Summary)), escapeMarkdown(tested))
	}
	return index.String(), nil
}
