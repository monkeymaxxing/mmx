// --- 7. Names that users read spell env, config, and dir one way.

// docs/changing-mmx/design/modules.md, "env, config, and dir have one spelling", gives
// three words one spelling in names: env for environment variables, config
// for configuration, and dir in a label without a verb, with directory in the
// plural and as a name's first word. Whether a label has a verb stays a call
// for review.

// otherMeaningsOfEnvironment are names in which "environment" does not mean
// environment variables, so the whole word stays.
var otherMeaningsOfEnvironment = []string{
	"virtual_environment", // Python's virtual environment (pip_package)
}

// namingTableFault says how a name breaks the naming table, or is empty.
func namingTableFault(name string) string {
	words := strings.FieldsFunc(strings.ToLower(name), func(r rune) bool { return r == '_' || r == '.' || r == '-' })
	for i, word := range words {
		switch {
		case (word == "environment" || word == "environments") && !slices.Contains(otherMeaningsOfEnvironment, name):
			return "write env for environment variables"
		case word == "configuration" || word == "configurations":
			return "write config for configuration"
		case word == "dirs":
			return "write directories in the plural"
		case word == "dir" && i == 0 && len(words) > 1:
			return "write directory as the first word"
		}
	}
	return ""
}

// namesUsersRead lists the YAML and JSON names of the Go code, the outputs of
// the core modules, and the inputs and outputs of the modules with a module
// description file, each with the place it comes from.
func namesUsersRead(t *testing.T, root string) map[string]string {
	t.Helper()
	names := map[string]string{}
	listed, err := exec.Command("git", "-C", root, "ls-files", "--", "cmd/*.go", "internal/*.go").Output()
	if err != nil {
		t.Fatalf("git ls-files: %v", err)
	}
	files := token.NewFileSet()
	for _, file := range strings.Fields(string(listed)) {
		if strings.HasSuffix(file, "_test.go") || slices.Contains(strings.Split(file, "/"), "testdata") {
			continue
		}
		parsed, err := parser.ParseFile(files, filepath.Join(root, file), nil, parser.SkipObjectResolution)
		if err != nil {
			t.Fatal(err)
		}
		ast.Inspect(parsed, func(n ast.Node) bool {
			field, ok := n.(*ast.Field)
			if !ok || field.Tag == nil {
				return true
			}
			tag, err := strconv.Unquote(field.Tag.Value)
			if err != nil {
				t.Fatal(err)
			}
			for _, key := range []string{"yaml", "json"} {
				if name, _, _ := strings.Cut(reflect.StructTag(tag).Get(key), ","); name != "" && name != "-" {
					position := files.Position(field.Pos())
					names[name] = fmt.Sprintf("%s:%d", file, position.Line)
				}
			}
			return true
		})
	}
	for _, module := range modules.CoreModules() {
		for _, result := range module.Description.Results {
			names[strings.TrimPrefix(result, "value.")] = "the results of the core module " + module.Name
		}
	}
	descriptions, err := filepath.Glob(filepath.Join(root, "*", "*", modules.ModuleDescriptionFile))
	if err != nil {
		t.Fatal(err)
	}
	examples, err := filepath.Glob(filepath.Join(root, "examples", "external-modules", "*", "*", modules.ModuleDescriptionFile))
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range append(descriptions, examples...) {
		directory := filepath.Dir(path)
		description, err := modules.ReadModuleDescription(directory, filepath.Base(directory))
		if err != nil {
			t.Fatal(err)
		}
		place, _ := filepath.Rel(root, path)
		for _, input := range description.Inputs {
			names[input.Name] = place
		}
		for _, output := range description.Outputs {
			names[output.Name] = place
		}
	}
	return names
}

func TestNamesFollowTheNamingTable(t *testing.T) {
	names := namesUsersRead(t, repositoryRoot(t))
	if len(names) < 500 {
		t.Fatalf("found only %d names, so this test checks too little", len(names))
	}
	for name, place := range names {
		if fault := namingTableFault(name); fault != "" {
			t.Errorf("%s: %s: %s (docs/changing-mmx/design/modules.md, section %q)", place, name, fault, "env, config, and dir have one spelling")
		}
	}
}

