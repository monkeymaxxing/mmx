// yamlBlock matches a fenced YAML block.
var yamlBlock = regexp.MustCompile("(?ms)^```yaml\n(.*?)^```")

// checkPageExamples loads each YAML block of a page whose first line that
// is neither empty nor a comment starts with "- " as the node tasks of one
// fleet stage, and returns a problem for each block that fails validation.
func checkPageExamples(t *testing.T, file string) []string {
	t.Helper()
	text, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	var problems []string
	for _, match := range yamlBlock.FindAllSubmatchIndex(text, -1) {
		block := string(text[match[2]:match[3]])
		if !isNodeTaskList(block) {
			continue
		}
		line := bytes.Count(text[:match[0]], []byte("\n")) + 1
		if err := loadNodeTaskExample(t.TempDir(), block); err != nil {
			problems = append(problems, fmt.Sprintf("%s:%d: the example does not pass validation: %v", file, line, err))
		}
	}
	return problems
}

func isNodeTaskList(block string) bool {
	for _, line := range strings.Split(block, "\n") {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, "#") {
			continue
		}
		return strings.HasPrefix(line, "- ")
	}
	return false
}

// variableReference matches .vars.NAME in an example.
var variableReference = regexp.MustCompile(`\.vars\.([A-Za-z_][A-Za-z0-9_]*)`)

// examplePublicKey is a public key line for an example's key file, its own
// for each file, so two key files never hold the same key.
func examplePublicKey(file string) string {
	seed := sha256.Sum256([]byte(file))
	publicKey, err := ssh.NewPublicKey(ed25519.NewKeyFromSeed(seed[:]).Public())
	if err != nil {
		panic(err)
	}
	return string(ssh.MarshalAuthorizedKey(publicKey))
}

// controllerFileRepairs make the files that an example names on the
// controller machine, such as a source, a template, or a key file, when
// validation reports one missing or unfit. Each matches validation's error
// and receives the path it names, absolute or relative to the project.
var controllerFileRepairs = []struct {
	errorText *regexp.Regexp
	repair    func(file string) error
}{
	{regexp.MustCompile(`(?:lstat|stat|open) (\S+): no such file or directory`), func(file string) error { return writeFile(file, "") }},
	{regexp.MustCompile(`open (\S+): not a directory`), makeDirectory},
	{regexp.MustCompile(`directory source (\S+): directory source must be a real directory`), makeDirectory},
	{regexp.MustCompile(`key file (\S+) holds no key line`), func(file string) error { return writeFile(file, examplePublicKey(file)) }},
	{regexp.MustCompile(`key directory (\S+) holds no file ending in \.pub`), func(directory string) error {
		file := filepath.Join(directory, "example.pub")
		return writeFile(file, examplePublicKey(file))
	}},
}

func makeDirectory(directory string) error {
	if err := os.RemoveAll(directory); err != nil {
		return err
	}
	return os.MkdirAll(directory, 0o755)
}

// loadNodeTaskExample validates an example as the node tasks of one fleet
// stage in a new project in directory. Each .vars.NAME it uses is 1 on the
// node. The files that the example names on the controller machine are made
// inside the project as validation asks for them, and validation runs again.
func loadNodeTaskExample(directory, block string) error {
	var variables strings.Builder
	for _, name := range slices.Compact(slices.Sorted(func(yield func(string) bool) {
		for _, match := range variableReference.FindAllStringSubmatch(block, -1) {
			if !yield(match[1]) {
				return
			}
		}
	})) {
		variables.WriteString("      " + name + ": 1\n")
	}
	inventory := "nodes:\n  web:\n    address: example.com\n"
	if variables.Len() > 0 {
		inventory += "    vars:\n" + variables.String()
	}
	var indented strings.Builder
	for _, line := range strings.Split(strings.TrimSuffix(block, "\n"), "\n") {
		if line != "" {
			indented.WriteString("      " + line)
		}
		indented.WriteString("\n")
	}
	files := map[string]string{
		"mmx_project_settings.yml": "project_name: example\ndefault_inventory: example\n",
		"inventories/example.yml":  inventory,
		"playbooks/example.yml":    "fleet_stages:\n  - id: example\n    nodes: all\n    node_tasks:\n" + indented.String(),
	}
	for name, text := range files {
		if err := writeFile(filepath.Join(directory, name), text); err != nil {
			return err
		}
	}
	repaired := map[string]bool{}
	for {
		_, _, err := config.Load(filepath.Join(directory, "mmx_project_settings.yml"), "example", "", nil)
		if err == nil {
			return nil
		}
		repairedNow := false
		for _, repair := range controllerFileRepairs {
			for _, match := range repair.errorText.FindAllStringSubmatch(err.Error(), -1) {
				file := match[1]
				if !filepath.IsAbs(file) {
					file = filepath.Join(directory, file)
				}
				inside, relativeErr := filepath.Rel(directory, filepath.Clean(file))
				key := repair.errorText.String() + " " + inside
				if relativeErr != nil || strings.HasPrefix(inside, "..") || repaired[key] {
					continue
				}
				if repairErr := repair.repair(file); repairErr != nil {
					return repairErr
				}
				repaired[key], repairedNow = true, true
			}
		}
		if !repairedNow {
			return err
		}
	}
}

func writeFile(file, text string) error {
	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		return err
	}
	return os.WriteFile(file, []byte(text), 0o644)
}

