// checkSharedSectionBackLinks returns a problem for each link of a module's
// page source to a section of a Markdown file outside internal/modules/ and
// docs/reference/modules/ whose text, up to the next heading of the same or a higher
// level, does not link to the module's generated page. A link to a file or
// heading that does not exist is the link test's problem.
func checkSharedSectionBackLinks(root, moduleName string) []string {
	source := pageSourceDirectory + "/" + moduleName + ".md"
	page := generatedPageDirectory + "/" + moduleName + ".md"
	text, err := os.ReadFile(filepath.Join(root, source))
	if err != nil {
		return []string{err.Error()}
	}
	var problems []string
	checked := map[string]bool{}
	for _, target := range linkTargets(string(text)) {
		if !isPathLink(target) || checked[target] {
			continue
		}
		checked[target] = true
		linkPath, anchor, hasAnchor := strings.Cut(target, "#")
		resolved := path.Clean(path.Join(pageSourceDirectory, linkPath))
		if !hasAnchor || path.Ext(resolved) != ".md" || path.Dir(resolved) == pageSourceDirectory || path.Dir(resolved) == generatedPageDirectory {
			continue
		}
		shared, err := os.ReadFile(filepath.Join(root, resolved))
		if err != nil {
			continue
		}
		section, found := sectionText(string(shared), anchor)
		if !found {
			continue
		}
		linksBack := slices.ContainsFunc(linkTargets(section), func(back string) bool {
			backPath, _, _ := strings.Cut(back, "#")
			return isPathLink(back) && path.Clean(path.Join(path.Dir(resolved), backPath)) == page
		})
		if !linksBack {
			problems = append(problems, fmt.Sprintf("%s links to %s; that section does not link back to %s", source, target, page))
		}
	}
	return problems
}

// sectionText returns the lines of the section with that anchor, from its
// heading to the next heading of the same or a higher level.
func sectionText(text, anchor string) (string, bool) {
	lines := strings.Split(text, "\n")
	headings := headingsOf(text)
	for i, heading := range headings {
		if heading.anchor != anchor {
			continue
		}
		end := len(lines)
		for _, next := range headings[i+1:] {
			if next.level <= heading.level {
				end = next.line
				break
			}
		}
		return strings.Join(lines[heading.line:end], "\n"), true
	}
	return "", false
}

